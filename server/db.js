'use strict';
/* BidVerse · BASE DE DATOS
   Dos motores con las mismas tablas y las mismas consultas:
     · PostgreSQL si existe la variable de entorno DATABASE_URL (en Render, con una base de datos gratis de Neon: los datos no se borran)
     · SQLite si no existe (en tu ordenador: un archivo en server/data/bidverse.db, incluido en Node 22.13+, no hay que instalar nada)
   Todo el SQL del juego está en este archivo.

   Tablas
     users     cuentas: nombre, contraseña (cifrada con scrypt + sal, nunca en claro), avatar y puntuación actual
     sessions  sesiones abiertas: el navegador guarda un código secreto y aquí solo se guarda su huella (SHA-256)
     matches   cada partida online entre dos cuentas: quién jugó, quién ganó y cuántos puntos ganó/perdió cada uno

   Puntos (sistema Elo, como en el ajedrez): todos empiezan con 1000. Al acabar una partida el ganador suma lo que pierde el rival.
   Ganar a alguien con más puntos da más (hasta 32); ganar a alguien mucho peor da poco. Empate: se acercan un poco.
   · Ranking histórico = la puntuación actual de cada cuenta.
   · Ranking semanal  = la suma de lo ganado/perdido desde el lunes a las 00:00 (UTC). Se calcula con la tabla matches,
     así que "se reinicia" sola cada semana sin borrar nada.
   Todas las funciones devuelven promesas (PostgreSQL va por red). */
const path = require('path'), fs = require('fs'), crypto = require('crypto'), { promisify } = require('util');

const scrypt = promisify(crypto.scrypt);
const START = 1000, K = 32, SESSION_DAYS = 60, DAY = 86400000;
const NAME_RE = /^[\p{L}\p{N}][\p{L}\p{N}._-]{2,15}$/u;  // 3-16 letras o números (también . _ -), sin espacios
const sha = s => crypto.createHash('sha256').update(s).digest('hex');
const keyOf = n => n.normalize('NFC').toLowerCase(); // "Goku" y "goku" son el mismo usuario

function cleanUser(s) { if (typeof s !== 'string' || s.length > 40) return null; const n = s.normalize('NFC').trim(); return NAME_RE.test(n) ? n : null; }
function cleanPass(s) { return typeof s === 'string' && s.length >= 6 && s.length <= 72 ? s : null; }

async function hashPass(pass) { const salt = crypto.randomBytes(16); const h = await scrypt(pass, salt, 32); return salt.toString('hex') + ':' + h.toString('hex'); }
async function checkPass(pass, stored) {
  const [salt, hex] = String(stored).split(':'); if (!salt || !hex) return false;
  const h = await scrypt(pass, Buffer.from(salt, 'hex'), 32), want = Buffer.from(hex, 'hex');
  return want.length === h.length && crypto.timingSafeEqual(h, want);
}
// Lunes de esta semana a las 00:00 UTC (en milisegundos)
function weekStart(now = Date.now()) { const d = new Date(now); d.setUTCHours(0, 0, 0, 0); d.setUTCDate(d.getUTCDate() - (d.getUTCDay() + 6) % 7); return d.getTime(); }
// Elo: puntos que gana el jugador A (el B gana lo mismo en negativo). sA = 1 gana A, 0 gana B, 0.5 empate
function elo(rA, rB, sA) { const eA = 1 / (1 + Math.pow(10, (rB - rA) / 400)); return Math.round(K * (sA - eA)); }

/* ---------- TABLAS (lo único que cambia entre los dos motores es cómo se numeran los id y el tamaño de las fechas) ---------- */
const schema = pg => `
  CREATE TABLE IF NOT EXISTS users (
    id         ${pg ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT'},
    name       TEXT    NOT NULL,
    name_key   TEXT    NOT NULL UNIQUE,
    pass       TEXT    NOT NULL,
    av         TEXT,
    rating     INTEGER NOT NULL DEFAULT ${START},
    created_at BIGINT  NOT NULL
  );
  CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT    PRIMARY KEY,
    user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at BIGINT  NOT NULL,
    last_seen  BIGINT  NOT NULL
  );
  CREATE TABLE IF NOT EXISTS matches (
    id        ${pg ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT'},
    cat       TEXT    NOT NULL,
    p1        INTEGER NOT NULL REFERENCES users(id),
    p2        INTEGER NOT NULL REFERENCES users(id),
    winner    INTEGER REFERENCES users(id),
    d1        INTEGER NOT NULL,
    d2        INTEGER NOT NULL,
    reason    TEXT    NOT NULL DEFAULT 'fight',
    played_at BIGINT  NOT NULL
  );
  CREATE INDEX IF NOT EXISTS matches_time ON matches(played_at);
  CREATE INDEX IF NOT EXISTS matches_p1 ON matches(p1);
  CREATE INDEX IF NOT EXISTS matches_p2 ON matches(p2);`;

/* ---------- ADAPTADORES: get (una fila), all (todas), run (sin resultado) y tx (transacción) con SQL escrito con ? ---------- */
function sqlite(file) {
  let DatabaseSync;
  try { ({ DatabaseSync } = require('node:sqlite')); } catch (e) {
    throw new Error('Para la base de datos local hace falta Node.js 22.13 o superior (trae SQLite incluido). Tienes ' + process.version + '. Descarga la versión LTS en https://nodejs.org');
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const db = new DatabaseSync(file), cache = new Map();
  db.exec('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON;' + schema(false));
  const st = sql => { let s = cache.get(sql); if (!s) { s = db.prepare(sql); cache.set(sql, s); } return s; };
  const T = { get: (sql, p = []) => st(sql).get(...p) || null, all: (sql, p = []) => st(sql).all(...p), run: (sql, p = []) => { st(sql).run(...p); } };
  // SQLite es una sola conexión: las operaciones van en fila para que nada se cuele en medio de una transacción
  let chain = Promise.resolve();
  const inLine = fn => { const p = chain.then(fn); chain = p.catch(() => {}); return p; };
  return {
    kind: 'SQLite', where: file, lock: '',
    get: (sql, p) => inLine(() => T.get(sql, p)), all: (sql, p) => inLine(() => T.all(sql, p)), run: (sql, p) => inLine(() => T.run(sql, p)),
    tx: fn => inLine(async () => { db.exec('BEGIN'); try { const r = await fn(T); db.exec('COMMIT'); return r; } catch (e) { db.exec('ROLLBACK'); throw e; } }),
    close: () => inLine(() => db.close()),
  };
}

async function postgres(url) {
  let pg;
  try { pg = require('pg'); } catch (e) { throw new Error('Falta el paquete "pg" para PostgreSQL. Ejecuta:  cd server  y luego  npm install'); }
  pg.types.setTypeParser(20, v => Number(v));   // BIGINT (fechas, COUNT, SUM) como número normal de JavaScript
  pg.types.setTypeParser(1700, v => Number(v)); // NUMERIC
  const local = /@(localhost|127\.0\.0\.1)(:\d+)?\//.test(url);
  const pool = new pg.Pool({ connectionString: url, max: 5, ssl: local ? false : true, idleTimeoutMillis: 30000 });
  pool.on('error', e => console.error('PostgreSQL:', e.message)); // una conexión que se cae sola no tumba el servidor
  const n = sql => { let i = 0; return sql.replace(/\?/g, () => '$' + (++i)); }; // ? -> $1, $2… (lo que usa PostgreSQL)
  const on = c => ({ get: async (sql, p = []) => (await c.query(n(sql), p)).rows[0] || null, all: async (sql, p = []) => (await c.query(n(sql), p)).rows, run: async (sql, p = []) => { await c.query(n(sql), p); } });
  const P = on(pool);
  await pool.query(schema(true));
  let host = '?'; try { host = new URL(url).hostname; } catch (e) { /* nada */ }
  return {
    kind: 'PostgreSQL', where: host, lock: ' FOR UPDATE', ...P,
    tx: async fn => { const c = await pool.connect(); try { await c.query('BEGIN'); const r = await fn(on(c)); await c.query('COMMIT'); return r; } catch (e) { await c.query('ROLLBACK').catch(() => {}); throw e; } finally { c.release(); } },
    close: () => pool.end(),
  };
}

/* ---------- CONSULTAS DEL JUEGO ---------- */
const RANK = (week) => `
  SELECT u.id, u.name, u.av, ${week ? 'SUM(CASE WHEN m.p1 = u.id THEN m.d1 ELSE m.d2 END)' : 'u.rating'} AS pts,
         SUM(CASE WHEN m.winner = u.id THEN 1 ELSE 0 END) AS w,
         SUM(CASE WHEN m.winner IS NOT NULL AND m.winner <> u.id THEN 1 ELSE 0 END) AS l,
         SUM(CASE WHEN m.winner IS NULL THEN 1 ELSE 0 END) AS d,
         COUNT(*) AS games
  FROM users u JOIN matches m ON (m.p1 = u.id OR m.p2 = u.id)${week ? ' AND m.played_at >= ?' : ''}
  GROUP BY u.id, u.name, u.av, u.rating, u.name_key
  ORDER BY pts DESC, w DESC, games ASC, u.name_key ASC`;

async function open({ url = process.env.DATABASE_URL, file = process.env.DB_PATH || path.join(__dirname, 'data', 'bidverse.db') } = {}) {
  const db = url ? await postgres(url) : sqlite(file);
  const pub = u => u && { id: u.id, name: u.name, av: u.av || null, rating: u.rating };
  const newSession = async uid => { const token = crypto.randomBytes(32).toString('hex'), now = Date.now(); await db.run('INSERT INTO sessions (token_hash, user_id, created_at, last_seen) VALUES (?, ?, ?, ?)', [sha(token), uid, now, now]); return token; };
  const byKey = name => db.get('SELECT * FROM users WHERE name_key = ?', [keyOf(name)]);
  await db.run('DELETE FROM sessions WHERE last_seen < ?', [Date.now() - SESSION_DAYS * DAY]); // limpia sesiones viejas al arrancar

  return {
    kind: db.kind, where: db.where,
    // Cuenta nueva. Devuelve { token, user } o { err: 'badName' | 'badPass' | 'taken' }
    async register(name, pass, av) {
      name = cleanUser(name); if (!name) return { err: 'badName' };
      if (!cleanPass(pass)) return { err: 'badPass' };
      if (await byKey(name)) return { err: 'taken' };
      const h = await hashPass(pass);
      let u;
      try { u = await db.get('INSERT INTO users (name, name_key, pass, av, created_at) VALUES (?, ?, ?, ?, ?) RETURNING *', [name, keyOf(name), h, av || null, Date.now()]); }
      catch (e) { if (await byKey(name)) return { err: 'taken' }; throw e; } // dos registros a la vez con el mismo nombre
      return { token: await newSession(u.id), user: pub(u) };
    },
    async login(name, pass) {
      const n = typeof name === 'string' ? name.normalize('NFC').trim() : '';
      const u = n && n.length <= 40 ? await byKey(n) : null;
      if (!u || typeof pass !== 'string' || pass.length > 72 || !(await checkPass(pass, u.pass))) return { err: 'wrong' };
      return { token: await newSession(u.id), user: pub(u) };
    },
    async logout(token) { if (typeof token === 'string') await db.run('DELETE FROM sessions WHERE token_hash = ?', [sha(token)]); },
    // Usuario de una sesión (o null si no existe o ha caducado)
    async byToken(token) {
      if (typeof token !== 'string' || !/^[0-9a-f]{64}$/.test(token)) return null;
      const h = sha(token), r = await db.get('SELECT s.last_seen, u.* FROM sessions s JOIN users u ON u.id = s.user_id WHERE s.token_hash = ?', [h]), now = Date.now();
      if (!r) return null;
      if (r.last_seen < now - SESSION_DAYS * DAY) { await db.run('DELETE FROM sessions WHERE token_hash = ?', [h]); return null; }
      if (now - r.last_seen > 3600000) await db.run('UPDATE sessions SET last_seen = ? WHERE token_hash = ?', [now, h]); // como mucho una escritura por hora y sesión
      return pub(r);
    },
    async setAvatar(uid, av) { await db.run('UPDATE users SET av = ? WHERE id = ?', [av || null, uid]); return pub(await db.get('SELECT * FROM users WHERE id = ?', [uid])); },
    // Guarda una partida y reparte los puntos, todo junto (transacción). uids = [cuenta del jugador 1, del jugador 2], w = 0 | 1 | -1 (empate)
    record({ cat, uids, w, reason = 'fight' }) {
      return db.tx(async t => {
        const rows = await t.all('SELECT id, rating FROM users WHERE id IN (?, ?) ORDER BY id' + db.lock, uids);
        const [a, b] = uids.map(id => rows.find(r => r.id === id));
        if (!a || !b) return null;
        const d = elo(a.rating, b.rating, w === 0 ? 1 : w === 1 ? 0 : .5);
        await t.run('UPDATE users SET rating = rating + ? WHERE id = ?', [d, a.id]);
        await t.run('UPDATE users SET rating = rating + ? WHERE id = ?', [-d, b.id]);
        await t.run('INSERT INTO matches (cat, p1, p2, winner, d1, d2, reason, played_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?)',
          [cat, a.id, b.id, w === 0 ? a.id : w === 1 ? b.id : null, d, -d, reason, Date.now()]);
        return { d: [d, -d], r: [a.rating + d, b.rating - d] };
      });
    },
    // Ranking: period 'week' | 'all'. Devuelve los 50 primeros y, si no está entre ellos, la fila del usuario que lo pide
    async ranking(period, uid) {
      const week = period === 'week', since = weekStart();
      const rows = (await db.all(RANK(week), week ? [since] : [])).map((r, i) => ({ pos: i + 1, id: r.id, name: r.name, av: r.av || null, pts: r.pts, w: r.w, l: r.l, d: r.d, games: r.games }));
      const mine = uid ? rows.find(r => r.id === uid) : null;
      const strip = r => r && { pos: r.pos, name: r.name, av: r.av, pts: r.pts, w: r.w, l: r.l, d: r.d, games: r.games, me: r.id === uid };
      return { period: week ? 'week' : 'all', since: week ? since : null, players: rows.length, rows: rows.slice(0, 50).map(strip), me: mine && mine.pos > 50 ? strip(mine) : null };
    },
    // Estadísticas de una cuenta: victorias/derrotas/empates por categoría, racha actual y sus últimas partidas
    async stats(uid) {
      const rows = await db.all(`SELECT m.cat, m.winner, m.reason, m.played_at, CASE WHEN m.p1 = ? THEN m.d1 ELSE m.d2 END AS d, o.name AS opp, o.av AS oav
        FROM matches m JOIN users o ON o.id = CASE WHEN m.p1 = ? THEN m.p2 ELSE m.p1 END
        WHERE m.p1 = ? OR m.p2 = ? ORDER BY m.played_at DESC, m.id DESC LIMIT 500`, [uid, uid, uid, uid]);
      const res = r => r.winner == null ? 'd' : r.winner === uid ? 'w' : 'l';
      const cats = {}, total = { w: 0, l: 0, d: 0 };
      for (const r of rows) { const c = cats[r.cat] || (cats[r.cat] = { w: 0, l: 0, d: 0 }), x = res(r); c[x]++; total[x]++; }
      let streak = 0; const first = rows.length ? res(rows[0]) : null; // racha: + victorias seguidas, - derrotas seguidas
      if (first && first !== 'd') for (const r of rows) { if (res(r) !== first) break; streak += first === 'w' ? 1 : -1; }
      return { total, cats, streak, recent: rows.slice(0, 10).map(r => ({ cat: r.cat, res: res(r), d: r.d, opp: r.opp, oav: r.oav || null, at: r.played_at, reason: r.reason })) };
    },
    close: () => db.close(),
  };
}

module.exports = { open, cleanUser, cleanPass, elo, weekStart, START };
